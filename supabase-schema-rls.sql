-- 1. TABLA DE PERFILES DE USUARIOS (Profiles / RBAC)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email TEXT UNIQUE NOT NULL,
  full_name TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'admin_ph', -- 'master_owner', 'admin_ph', 'supervisor', 'porteria', 'residente'
  tenant_id TEXT DEFAULT 'ten_01',
  is_active BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2. TABLA DE COPROPIEDADES (Tenants / Conjuntos Residenciales)
CREATE TABLE IF NOT EXISTS public.tenants (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  nit TEXT NOT NULL,
  city TEXT NOT NULL DEFAULT 'Medellín',
  zone TEXT DEFAULT 'El Poblado',
  admin_name TEXT,
  admin_email TEXT,
  units_count INT DEFAULT 100,
  plan TEXT DEFAULT 'Plan Enterprise',
  status TEXT DEFAULT 'Activa 🟢',
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 3. TABLA DE REPORTES DE PORTERÍA & MANTENIMIENTO (Sincronización en Tiempo Real)
CREATE TABLE IF NOT EXISTS public.maintenance_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL DEFAULT 'ten_01',
  category TEXT NOT NULL DEFAULT 'Infraestructura / Daño',
  location TEXT NOT NULL,
  description TEXT NOT NULL,
  vigilante_name TEXT NOT NULL DEFAULT 'Guarda en Turno',
  status TEXT NOT NULL DEFAULT 'Reportado',
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 4. TABLA DE MINUTA DIGITAL DE VIGILANCIA
CREATE TABLE IF NOT EXISTS public.minuta_digital_ph (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL DEFAULT 'ten_01',
  tipo_novedad TEXT NOT NULL DEFAULT 'Ronda Preventiva',
  guarda TEXT NOT NULL DEFAULT 'Guarda en Turno',
  descripcion TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 5. TABLA DE AUDITORÍA INMUTABLE SHA-256 (Append-Only)
CREATE TABLE IF NOT EXISTS public.audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL DEFAULT 'ten_01',
  user_executor TEXT NOT NULL,
  action_type TEXT NOT NULL,
  details TEXT NOT NULL,
  signature_hash TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

